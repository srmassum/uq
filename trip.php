<?php
/**
 * My trip — the places you want to go, as opposed to the ones you have been to.
 *
 * This is the one page on the site whose content the server does not know. The
 * list lives in the browser (localStorage, see assets/js/trip.js), so PHP cannot
 * render the rows; what it can do is hand over the catalogue once and let the
 * client pick from it. That is a deliberate trade:
 *
 *   - the page has no login and no server-side list, so there is nothing to leak
 *     and nothing to moderate;
 *   - it works with the database behind a cache, because the payload is content,
 *     not state;
 *   - the cost is that the whole place index ships with the page. Sixty rows of
 *     name, municipality and duration is a few kilobytes, which is why it is
 *     worth it and why inc/places.php selects only those columns for it.
 *
 * The page is also where a "want to go" list becomes useful rather than just
 * satisfying: it adds the visit times up and prints the whole thing as text, so
 * it can be pasted into a message to whoever is coming with you.
 */

declare(strict_types=1);

require __DIR__ . '/inc/bootstrap.php';
require __DIR__ . '/inc/places.php';
require __DIR__ . '/inc/itineraries.php';
require __DIR__ . '/inc/layout.php';

$ready = places_ready();
$index = $ready ? places_index() : [];

// The empty state offers a second way in. Somebody looking at an empty trip is
// exactly the person a ready-made plan is for — it fills the list in one press
// — so the link is worth one more count, and it is only shown when there is
// actually something behind it.
$hasPlans = itineraries_ready();

page_head([
    'nav'      => 'trip',
    'title'    => t('trip.title'),
    'desc'     => t('trip.sub'),
    // The list is private to one browser, so there is nothing here worth
    // indexing: a search result for it would show every visitor an empty page.
    'noindex'  => true,
]);
?>

<section class="wrap hero compact">
  <span class="pill brand" data-trip-has hidden>
    <span data-trip-count>0</span> · <?= e(t('trip.title')) ?>
  </span>
  <h1><?= e(t('trip.title')) ?></h1>
  <p class="lede"><?= e(t('trip.sub')) ?></p>
</section>

<?php if (!$ready): ?>

  <section class="wrap narrow">
    <div class="panel">
      <h2>No places loaded yet</h2>
      <p>The trip is built out of the places guide, and that table is empty or missing.</p>
      <p>Import <code>sql/schema.sql</code>, <code>sql/seed-core.sql</code>,
         <code>sql/seed.sql</code> and <code>sql/seed-places.sql</code> in phpMyAdmin, in that
         order. The last two are generated by
         <a href="<?= e(APP_BASE) ?>/setup/prepare.php"><code>setup/prepare.php</code></a>.</p>
    </div>
  </section>

<?php else: ?>

<div class="wrap" data-trip-page>

  <?php // Shown until trip-page.js has read the list. Without it the page would
        // flash its empty state at somebody who has twenty places saved. ?>
  <noscript>
    <?php // Not the empty state: somebody reading this may well have a full trip
          // saved, and the server genuinely cannot tell. So the message is about
          // why the page is blank rather than a claim about their list. ?>
    <div class="panel">
      <h2><?= e(t('trip.title')) ?></h2>
      <p class="muted"><?= e(t('trip.needs_js')) ?></p>
    </div>
  </noscript>

  <p class="muted" data-trip-loading><?= e(t('trip.loading')) ?></p>

  <div class="trip-head panel" hidden data-trip-summary>
    <div class="trip-figures">
      <div class="trip-figure">
        <span class="trip-num" data-trip-total-count>0</span>
        <?php // Filled by the script, which also has to choose between the
              // singular and the plural — so the label is built there and this
              // element starts empty rather than carrying a half-sentence. ?>
        <span class="muted" data-trip-total-label></span>
      </div>
      <div class="trip-figure">
        <span class="trip-num" data-trip-total-time>—</span>
        <?php // Swapped by the script for "No times recorded for these" when no
              // place on the trip has a duration, because a caption reading
              // "Time at these places" over a dash is a sentence that answers a
              // question the figure just declined to answer. ?>
        <span class="muted" data-trip-total-caption><?= e(t('trip.total')) ?></span>
      </div>
    </div>

    <p class="muted trip-note" data-trip-unknown hidden></p>
    <p class="muted trip-note" data-trip-travel-note><?= e(t('trip.travel_note')) ?></p>

    <div class="trip-actions">
      <button class="btn primary" type="button" data-trip-copy><?= e(t('trip.copy')) ?></button>
      <a class="btn" href="<?= e(APP_BASE) ?>/index.php" data-trip-map><?= e(t('trip.see_map')) ?></a>
      <button class="btn ghost" type="button" data-trip-clear><?= e(t('trip.clear')) ?></button>
    </div>
  </div>

  <?php // A place can be unpublished or binned after somebody added it. The list
        // is in their browser, so the site cannot clean it up — the honest thing
        // is to name them and offer a way to drop them. ?>
  <div class="panel trip-gone" hidden data-trip-gone-panel>
    <p class="muted" data-trip-gone-note></p>
    <ul class="trip-gone-list" data-trip-gone-list></ul>
  </div>

  <?php // A numbered list rather than a card grid: a trip is a plan, and a plan
        // is read top to bottom in the order you intend to travel it. The order
        // is the order the places were added, which is the only order the site
        // can honestly claim to know. ?>
  <ol class="trip-list" data-trip-list hidden></ol>

  <div class="panel trip-empty" hidden data-trip-empty>
    <h2><?= e(t('trip.empty')) ?></h2>
    <p class="muted"><?= e(t('trip.empty_hint')) ?></p>
    <p class="trip-actions">
      <a class="btn primary" href="<?= e(APP_BASE) ?>/places.php"><?= e(t('trip.empty_cta')) ?></a>
      <?php if ($hasPlans): ?>
        <?php // A whole day's worth of places in one press, which is the shortest
              // path from an empty list to one worth sending to somebody. ?>
        <a class="btn" href="<?= e(APP_BASE) ?>/itineraries.php"><?= e(t('trip.empty_plans')) ?></a>
      <?php endif; ?>
    </p>
  </div>

  <p class="muted trip-note trip-device"><?= e(t('trip.on_device')) ?></p>
</div>

<?php endif; ?>

<?php
// The catalogue, then the renderer.
//
// The page's own strings travel with the payload rather than in a second global,
// because the renderer is the only thing that reads them and they are all built
// the same way. Everything is escaped with json_encode's HEX_* flags rather than
// printed raw into a <script>, so a place name containing "</script>" cannot end
// the block early — the same treatment the QPLACES payload gets.
//
// trip.js itself is emitted by page_foot(); only the page renderer is added here.
$payload = json_encode(
    [
        'p'       => $index,
        'lang'    => current_lang(),
        'base'    => APP_BASE,
        'strings' => [
            'count'         => t('trip.count'),
            'count_one'     => t('trip.count_one'),
            'total'         => t('trip.total'),
            'total_none'    => t('trip.total_none'),
            'unknown'       => t('trip.unknown'),
            'copy'          => t('trip.copy'),
            'copied'        => t('trip.copied'),
            'copy_failed'   => t('trip.copy_failed'),
            'copy_head'     => t('trip.copy_head'),
            'copy_total'    => t('trip.copy_total'),
            'copy_gone'     => t('trip.copy_gone'),
            'clear'         => t('trip.clear'),
            'clear_confirm' => t('trip.clear_confirm'),
            'remove'        => t('trip.remove'),
            'open'          => t('trip.open'),
            'gone'          => t('trip.gone'),
            'gone_note'     => t('trip.gone_note'),
        ],
    ],
    JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT
);

$scripts = '<script>window.QTRIP_DATA = ' . $payload . ";</script>\n";

if ($ready) {
    $scripts .= '<script src="' . e(asset('assets/js/trip-page.js')) . "\" defer></script>\n";
}

page_foot(['scripts' => $scripts]);
