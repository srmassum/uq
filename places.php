<?php
/**
 * The places guide — browse and filter everything worth the drive.
 *
 * Filters live in the query string rather than in JavaScript state, for two
 * reasons: a filtered view is a link someone can send to a friend ("the free
 * beaches in Al Wakrah"), and every filter still works with scripting off. The
 * four toggle chips are therefore links inside the form, and only the search box
 * and the three selects actually submit it.
 *
 * The one thing JavaScript does here is "Near me": the browser is the only
 * party that knows where the visitor is, and the cards already carry their
 * coordinates, so sorting happens without a round trip.
 */

declare(strict_types=1);

require __DIR__ . '/inc/bootstrap.php';
require __DIR__ . '/inc/places.php';
require __DIR__ . '/inc/layout.php';

/** A link back to this page with a filter set applied. */
function guide_url(array $f, string $sort): string
{
    $qs = places_query($f, $sort);
    return APP_BASE . '/places.php' . ($qs === '' ? '' : '?' . $qs);
}

$f       = places_read_filters($_GET);
$sortKey = places_sort_key($_GET);
$ready   = places_ready();

$muns  = $ready ? places_municipalities() : [];
$cats  = $ready ? places_categories() : [];
$all   = $ready ? places_count([]) : 0;
$rows  = $ready ? places_list($f, $sortKey) : [];
$shown = count($rows);

// The filters are part of the address: they are read on the server, a link
// carrying them opens the same list, and "free places in Al Wakrah" is a real
// page somebody would want to find. Sorted order and the search box are not —
// the same places in a different order are the same page, and a search result
// is nobody's idea of a destination — so neither reaches the canonical.
$canonFilters = $f;
unset($canonFilters['q']);
$canonical = 'places.php' . ($canonFilters === [] ? '' : '?' . http_build_query($canonFilters));

page_head([
    'nav'       => 'places',
    'title'     => t('places.title'),
    'desc'      => t('places.sub'),
    'canonical' => $canonical,
]);
?>

<section class="wrap hero compact">
  <span class="pill brand"><?= e(t('places.results', [':n' => num((string) $all)])) ?></span>
  <h1><?= e(t('places.title')) ?></h1>
  <p class="lede"><?= e(t('places.sub')) ?></p>
</section>

<?php if (!$ready): ?>

  <section class="wrap narrow">
    <div class="panel">
      <h2>No places loaded yet</h2>
      <p>The guide reads from MySQL, and the places table is empty or missing.</p>
      <p>Import <code>sql/schema.sql</code>, <code>sql/seed-core.sql</code>,
         <code>sql/seed.sql</code> and <code>sql/seed-places.sql</code> in phpMyAdmin, in that
         order. The last two are generated by
         <a href="<?= e(APP_BASE) ?>/setup/prepare.php"><code>setup/prepare.php</code></a>.</p>
    </div>
  </section>

<?php else: ?>

<div class="wrap">

  <form class="filters" method="get" action="<?= e(APP_BASE) ?>/places.php" id="filters-form">
    <?php
    // The toggles are links, not checkboxes: each one is a shareable URL, the
    // pressed state is styled already, and none of them need JavaScript.
    // aria-current rather than aria-pressed, since these are links — pressed
    // is a button state, and the CSS matches both.
    foreach ([
        'free'   => t('places.free'),
        'hidden' => t('places.hidden'),
        'family' => t('places.family'),
        'metro'  => t('places.metro'),
    ] as $key => $label):
        $next = $f;
        if (isset($next[$key])) { unset($next[$key]); } else { $next[$key] = '1'; }
    ?>
      <a class="chip" href="<?= e(guide_url($next, $sortKey)) ?>"
         aria-current="<?= isset($f[$key]) ? 'true' : 'false' ?>"><?= e($label) ?></a>
    <?php endforeach; ?>

    <?php // Carry the link-chips through a form submit. ?>
    <?php foreach (['free', 'hidden', 'family', 'metro'] as $k): ?>
      <?php if (isset($f[$k])): ?><input type="hidden" name="<?= e($k) ?>" value="1"><?php endif; ?>
    <?php endforeach; ?>

    <label class="sr" for="f-q"><?= e(t('places.search_ph')) ?></label>
    <input class="search" id="f-q" type="search" name="q" autocomplete="off"
           value="<?= e((string) ($f['q'] ?? '')) ?>"
           placeholder="<?= e(t('places.search_ph')) ?>">

    <label class="sr" for="f-mun"><?= e(t('places.all_mun')) ?></label>
    <select id="f-mun" name="mun">
      <option value=""><?= e(t('places.all_mun')) ?></option>
      <?php foreach ($muns as $m): ?>
        <option value="<?= e($m['code']) ?>"<?= ($f['mun'] ?? '') === $m['code'] ? ' selected' : '' ?>>
          <?= e(pick($m, 'name')) ?> (<?= e(num((string) $m['n'])) ?>)
        </option>
      <?php endforeach; ?>
    </select>

    <label class="sr" for="f-cat"><?= e(t('places.all_cats')) ?></label>
    <select id="f-cat" name="cat">
      <option value=""><?= e(t('places.all_cats')) ?></option>
      <?php foreach ($cats as $c): ?>
        <option value="<?= e($c['slug']) ?>"<?= ($f['cat'] ?? '') === $c['slug'] ? ' selected' : '' ?>>
          <?= e($c['icon']) ?> <?= e(pick($c, 'name')) ?> (<?= e(num((string) $c['n'])) ?>)
        </option>
      <?php endforeach; ?>
    </select>

    <label class="sr" for="f-sort"><?= e(t('places.sort_default')) ?></label>
    <select id="f-sort" name="sort">
      <option value=""<?= $sortKey === 'default' ? ' selected' : '' ?>><?= e(t('places.sort_default')) ?></option>
      <option value="name"<?= $sortKey === 'name' ? ' selected' : '' ?>><?= e(t('places.sort_name')) ?></option>
      <option value="mun"<?= $sortKey === 'mun' ? ' selected' : '' ?>><?= e(t('places.sort_mun')) ?></option>
      <option value="fee"<?= $sortKey === 'fee' ? ' selected' : '' ?>><?= e(t('places.sort_fee')) ?></option>
    </select>

    <?php // Redundant once the selects submit themselves, but it is the only
          // way to apply a filter with scripting off, so it stays visible. ?>
    <button class="btn sm" type="submit"><?= e(t('places.filters')) ?></button>

    <?php // Unhidden by places.js: a button that cannot work should not be offered. ?>
    <button class="btn sm ghost" type="button" id="near-me" data-near hidden>
      <?= e(t('places.near_me')) ?>
    </button>

    <?php if ($f !== [] || $sortKey !== 'default'): ?>
      <a class="btn sm ghost" href="<?= e(APP_BASE) ?>/places.php"><?= e(t('places.clear_filters')) ?></a>
    <?php endif; ?>
  </form>

  <p class="muted results-line">
    <span><?php
      if ($f === []) {
          echo e($shown === 1 ? t('places.results_one') : t('places.results', [':n' => num((string) $shown)]));
      } else {
          echo e(t('places.showing', [':n' => num((string) $shown), ':total' => num((string) $all)]));
      }
    ?></span>
    <span class="near-note" id="near-note" hidden></span>
  </p>

  <?php if ($rows === []): ?>
    <p class="empty"><?= e(t('places.none')) ?></p>
  <?php else: ?>

    <div class="place-grid" id="place-grid">
      <?php foreach ($rows as $p): ?>
        <?php
        $color = (string) ($p['cat']['color'] ?? '');
        $icon  = (string) ($p['cat']['icon'] ?? '');
        $href  = APP_BASE . '/place.php?' . http_build_query([
            'slug' => (string) $p['slug'],
            'from' => places_query($f, $sortKey),
        ]);
        ?>
        <?php // The wishlist button is a sibling of the card link, not a child:
              // a <button> inside an <a> is invalid, and every click on it would
              // also follow the link. The wrapper exists only to position it. ?>
        <div class="card-cell">
          <a class="place-card" href="<?= e($href) ?>"
             data-lat="<?= e((string) $p['lat']) ?>" data-lng="<?= e((string) $p['lng']) ?>">
            <div class="thumb"<?= $color !== '' ? ' style="--c:' . e($color) . '"' : '' ?>>
              <span aria-hidden="true"><?= e($icon !== '' ? $icon : '📍') ?></span>
            </div>

            <div class="body">
              <h3><?= e(pick($p, 'name')) ?></h3>
              <p class="sm"><?= e(pick($p, 'summary')) ?></p>
              <p class="sm where"><?= e(pick($p['mun'], 'name')) ?><?php
                if ($p['loc'] !== null): ?> · <?= e(pick($p['loc'], 'name')) ?><?php
                endif; ?></p>

              <div class="meta">
                <?php foreach (places_tags($p) as $tag): ?>
                  <?php if ($tag['kind'] === 'cat' && $tag['color'] !== ''): ?>
                    <span class="pill" style="border-color:transparent;background:color-mix(in srgb, <?= e($tag['color']) ?> 14%, transparent);color:<?= e($tag['color']) ?>">
                      <?= e($tag['icon']) ?> <?= e($tag['text']) ?>
                    </span>
                  <?php elseif ($tag['kind'] === 'fee' && !empty($tag['free'])): ?>
                    <span class="pill ok"><?= e($tag['text']) ?></span>
                  <?php else: ?>
                    <span class="pill"><?= e($tag['text']) ?></span>
                  <?php endif; ?>
                <?php endforeach; ?>

                <?php $dur = places_duration($p['duration_mins'] === null ? null : (int) $p['duration_mins']); ?>
                <?php if ($dur !== ''): ?><span class="pill"><?= e($dur) ?></span><?php endif; ?>
              </div>
            </div>
          </a>

          <?php // data-trip-name is what the toast and the screen-reader label
                // use, so trip.js never has to read the card's own text. ?>
          <button class="trip-btn" type="button"
                  data-trip="<?= e((string) $p['slug']) ?>"
                  data-trip-name="<?= e(pick($p, 'name')) ?>"
                  aria-pressed="false">
            <span class="trip-ico" aria-hidden="true">♡</span>
          </button>
        </div>
      <?php endforeach; ?>
    </div>

  <?php endif; ?>
</div>

<?php endif; ?>

<?php
$scripts = '<script>window.QPLACES = '
    . json_encode(['strings' => [
        'locating'    => t('geo.locating'),
        'denied'      => t('geo.denied'),
        'unavailable' => t('geo.unavailable'),
        'unsupported' => t('geo.unsupported'),
        'done'        => t('places.near_done'),
        'distance'    => t('places.distance'),
    ]], JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT)
    . ';</script>' . "\n"
    . '<script src="' . e(asset('assets/js/places.js')) . '" defer></script>' . "\n";

page_foot(['scripts' => $scripts]);
